// Generate the shipped demo analysis with an official local UCI engine.
// Usage: node tests/prepare-demo-analysis.cjs <stockfish.exe> [depth=20]
const {spawn}=require('node:child_process'),fs=require('node:fs'),path=require('node:path'),readline=require('node:readline');
const S=require('../review/core.js');
const exe=process.argv[2],depth=Number(process.argv[3]||20);
if(!exe||!Number.isInteger(depth)||depth<20)throw Error('Supply the official Stockfish executable and depth >= 20.');
const root=path.resolve(__dirname,'..'),checkpoint=path.join(root,'android/recorder/build/reports/demo-analysis-progress.json');
const processEngine=spawn(exe,[],{windowsHide:true});
const lines=readline.createInterface({input:processEngine.stdout});
let waiter=null,engineName='',latest={},active=false;
lines.on('line',line=>{
 if(line.startsWith('id name '))engineName=line.slice(8);
 if(active&&line.startsWith('info depth ')&&line.includes(' pv ')&&!/ (lowerbound|upperbound)( |$)/.test(line)){
  const d=Number(line.match(/\bdepth (\d+)/)?.[1]),mp=Number(line.match(/\bmultipv (\d+)/)?.[1]||1),score=line.match(/\bscore (cp|mate) (-?\d+)/),pv=line.split(' pv ')[1].trim().split(/\s+/);
  if(score)latest[mp]={depth:d,cp:score[1]==='cp'?Number(score[2]):null,mate:score[1]==='mate'?Number(score[2]):null,pv};
 }
 if(waiter&&line.startsWith(waiter.prefix)){const done=waiter;waiter=null;clearTimeout(done.timer);done.resolve(line);}
});
function command(input,prefix,timeout=180000){
 return new Promise((resolve,reject)=>{waiter={prefix,resolve,reject,timer:setTimeout(()=>{waiter=null;reject(Error('Timed out: '+input));},timeout)};processEngine.stdin.write(input+'\n');});
}
processEngine.on('error',e=>{if(waiter){clearTimeout(waiter.timer);waiter.reject(e);waiter=null;}});
async function main(){
 const record=S.demo(),rows=S.timeline(record);
 const cached=fs.existsSync(checkpoint)?JSON.parse(fs.readFileSync(checkpoint,'utf8')):{engine:'',analysis:{}};
 await command('uci','uciok');if(engineName!=='Stockfish 19')throw Error('Expected Stockfish 19, got '+engineName);
 processEngine.stdin.write('setoption name Threads value 4\nsetoption name Hash value 256\nsetoption name MultiPV value 3\n');
 await command('isready','readyok');
 const analysis={};
 for(const [i,row] of rows.entries()){
  const game=S.position(record,i);
  if(game.game_over()){
   analysis[row.fen]={engine:engineName,budget:0,precomputed:true,lines:[{cp:game.in_checkmate()?(game.turn()==='w'?-100000:100000):0,mate:game.in_checkmate()?0:null,depth:0,terminal:true,pv:[]}]};
  }else if(cached.engine===engineName&&cached.analysis[row.fen]?.lines.every(l=>l.depth>=depth)){
   analysis[row.fen]=cached.analysis[row.fen];
  }else{
   processEngine.stdin.write('ucinewgame\n');await command('isready','readyok');
   latest={};active=true;const start=Date.now();
   await command('position fen '+record.initialFen+(i?' moves '+record.moves.slice(0,i).join(' '):'')+'\ngo depth '+depth,'bestmove ');
   active=false;
   const values=Object.keys(latest).sort((a,b)=>a-b).map(k=>latest[k]),sign=game.turn()==='w'?1:-1;
   if(values.length!==Math.min(3,game.moves().length)||values.some(l=>l.depth<depth))throw Error('Incomplete deep analysis at ply '+i);
   values.forEach(l=>{if(l.cp!==null)l.cp*=sign;if(l.mate!==null)l.mate*=sign;S.position({...record,initialFen:row.fen,moves:l.pv});});
   analysis[row.fen]={engine:engineName,budget:Date.now()-start,precomputed:true,lines:values};
  }
  fs.writeFileSync(checkpoint,JSON.stringify({engine:engineName,depth,analysis},null,2));
  console.log(`Analyzed ${i+1}/${rows.length}, minimum depth ${Math.min(...analysis[row.fen].lines.map(l=>l.depth))}`);
 }
 const data={engine:engineName,depth,threads:4,multiPV:3,source:'https://github.com/official-stockfish/Stockfish/releases/tag/sf_19',moves:record.moves,analysis};
 const output=path.join(root,'review/demo-analysis.js');
 fs.writeFileSync(output,"// Generated by tests/prepare-demo-analysis.cjs; see demo-analysis.md.\n(function(root){const data="+JSON.stringify(data,null,2)+";if(typeof module==='object')module.exports=data;else root.OscarDemo=data;})(typeof window!=='undefined'?window:globalThis);\n");
 console.log('Saved '+output);
}
main().catch(e=>{console.error(e);process.exitCode=1;}).finally(()=>{processEngine.stdin.end('quit\n');processEngine.kill();lines.close();});
